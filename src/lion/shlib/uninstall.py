"""Planning and application of ``lion shlib uninstall``."""

from __future__ import annotations

import re
import shlex
import stat
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from lion.shlib.errors import ShlibError
from lion.shlib.files import atomic_write
from lion.shlib.layout import ShlibLayout

SECRETS_NAME = "secrets.sh"

_HEADER = (
    b"# Generated by `lion shlib uninstall`.\n"
    b"# This file combines the former shlib exports and shlib files; "
    b"it does not use the shlib mechanism.\n"
)

_SECRETS_HEADER = (
    b"# Generated by `lion shlib uninstall`.\n"
    b"# Owner-only exports from ~/.shlib/exports. Mode 0600.\n"
    b"# This file is sourced by ~/.zshrc. Delete or move it only deliberately.\n"
)

_EXPORT_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


@dataclass(frozen=True, slots=True)
class FlattenedConfig:
    """Flattened content assembled from a shlib tree.

    Attributes:
        content: Exact bytes for the new ``.zshrc``.
        export_names: Names of the public exported files, in write order.
        secret_names: Names of the owner-only exported files, in write order.
        secrets_content: Exact bytes for ``secrets.sh``, or ``None`` when there
            are no owner-only exports.
        secrets_path: Planned location of ``secrets.sh`` inside the backup.
        shlib_files: Sourced shlib files, in write order.
    """

    content: bytes
    export_names: tuple[str, ...]
    secret_names: tuple[str, ...]
    secrets_content: bytes | None
    secrets_path: Path
    shlib_files: tuple[Path, ...]


@dataclass(frozen=True, slots=True)
class UninstallPlan:
    """Validated work for a shlib uninstallation.

    Attributes:
        layout: Paths below the selected home directory.
        zshrc: Flattened configuration file.
        backup: Destination of the former shlib root.
        content: Exact bytes for the flattened ``.zshrc``.
        zshrc_mode: Permission bits for the flattened file.
        export_names: Names of the public exported values.
        secret_names: Names of the owner-only exported values.
        secrets_content: Exact bytes for ``secrets.sh``, or ``None``.
        secrets_path: Planned location of ``secrets.sh`` inside the backup.
        shlib_files: Sourced shlib files.
        warnings: Non-fatal notices, for example a forced drift override.
        zshrc_exists: Whether ``.zshrc`` exists before the uninstallation.
    """

    layout: ShlibLayout
    zshrc: Path
    backup: Path
    content: bytes
    zshrc_mode: int
    export_names: tuple[str, ...]
    secret_names: tuple[str, ...]
    secrets_content: bytes | None
    secrets_path: Path
    shlib_files: tuple[Path, ...]
    warnings: tuple[str, ...]
    zshrc_exists: bool


@dataclass(frozen=True, slots=True)
class UninstallReport:
    """Result of a successful shlib uninstallation.

    Attributes:
        zshrc: Flattened configuration file.
        backup: Backup directory that holds the former shlib tree.
        export_names: Names of the public exported values.
        secret_names: Names of the owner-only exported values.
        secrets_path: Location of ``secrets.sh`` inside the backup.
        shlib_files: Sourced shlib files.
        warnings: Non-fatal notices produced during planning.
    """

    zshrc: Path
    backup: Path
    export_names: tuple[str, ...]
    secret_names: tuple[str, ...]
    secrets_path: Path
    shlib_files: tuple[Path, ...]
    warnings: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class _Exports:
    """Exports split by whether they are readable by group or others."""

    public_names: tuple[str, ...]
    public_lines: tuple[bytes, ...]
    secret_names: tuple[str, ...]
    secret_lines: tuple[bytes, ...]


def flatten(layout: ShlibLayout, backup: Path) -> FlattenedConfig:
    """Combine all exports and shlib files into one configuration.

    Selection and ordering mirror the bootstrap block: exports are regular,
    non-hidden files in ``exports/`` sorted by name, and shlibs are regular
    files whose names start with two ASCII digits. Files whose permission bits
    grant no access to group or others are owner-only: they are not written
    into the flattened ``.zshrc`` but into ``secrets.sh`` inside ``backup``.

    Args:
        layout: Paths below the selected home directory.
        backup: Planned backup directory of the former shlib root. It is used
            for the ``secrets.sh`` path in the flattened file.

    Returns:
        The flattened configuration and the files that contributed to it.

    Raises:
        ShlibError: If the shlib directory is missing, a file cannot be read,
            an export name is invalid or an export value contains a NUL byte.
    """
    shlibs = layout.shlibs
    if not shlibs.is_dir():
        raise ShlibError(f"{shlibs} is missing; refusing to build a flattened .zshrc from a damaged tree")

    exports = _read_exports(layout.exports)
    shlib_files, shlib_chunks = _read_shlibs(shlibs)
    secrets_path = backup / SECRETS_NAME

    chunks = [_HEADER, b"\n# >>> exports\n", *exports.public_lines, b"# <<< exports\n"]
    secrets_content: bytes | None = None
    if exports.secret_lines:
        secrets_content = _SECRETS_HEADER + b"".join(exports.secret_lines)
        chunks.append(b"\n")
        chunks.extend(_secret_block(secrets_path, len(exports.secret_names)))
    if shlib_chunks:
        chunks.append(b"\n")
        chunks.extend(shlib_chunks)

    return FlattenedConfig(
        content=b"".join(chunks),
        export_names=exports.public_names,
        secret_names=exports.secret_names,
        secrets_content=secrets_content,
        secrets_path=secrets_path,
        shlib_files=shlib_files,
    )


def plan_uninstall(layout: ShlibLayout, *, force: bool = False) -> UninstallPlan:
    """Preflight a shlib uninstallation without changing the filesystem.

    All files that contribute to the flattened ``.zshrc`` are read and
    validated here, so a failure cannot leave a half-written output. The
    backup path is fixed before rendering because owner-only exports are
    sourced from ``secrets.sh`` inside that backup.

    Args:
        layout: Paths below the selected home directory.
        force: Allow a missing lock file or a ``.zshrc`` that differs from the
            lock file.

    Returns:
        The validated uninstallation plan.

    Raises:
        ShlibError: If the shlib tree is damaged, the ``.zshrc`` cannot be
            read or the lock check requires ``--force``.
    """
    root = layout.root
    if root.is_symlink():
        raise ShlibError(f"{root} is a symlink; refusing to uninstall it")
    if not root.is_dir():
        raise ShlibError(f"{root} does not exist; nothing to uninstall")
    if not layout.shlibs.is_dir():
        raise ShlibError(f"{layout.shlibs} is missing; refusing to guess from a damaged shlib tree")

    zshrc = layout.zshrc
    if zshrc.is_symlink():
        raise ShlibError(f"{zshrc} is a symlink; shlib does not overwrite symlinked configuration files")

    warnings: list[str] = []
    zshrc_exists = zshrc.exists()
    if zshrc_exists:
        if not zshrc.is_file():
            raise ShlibError(f"{zshrc} is not a regular file")
        try:
            current = zshrc.read_bytes()
            zshrc_mode = stat.S_IMODE(zshrc.stat().st_mode)
        except OSError as exc:
            raise ShlibError(f"cannot read {zshrc}: {exc}") from exc

        lock_file = layout.lock_file
        if lock_file.is_file():
            try:
                locked = lock_file.read_bytes()
            except OSError as exc:
                raise ShlibError(f"cannot read {lock_file}: {exc}") from exc
            if current != locked:
                if not force:
                    raise ShlibError(f"{zshrc} differs from {lock_file}; review the difference or rerun with --force")
                warnings.append(f"{zshrc} differs from {lock_file}; continuing because --force was given")
        elif not force:
            raise ShlibError(f"{lock_file} is missing; rerun with --force to discard manual .zshrc changes")
        else:
            warnings.append(f"{lock_file} is missing; continuing because --force was given")
    else:
        zshrc_mode = 0o644

    backup = _backup_path(root, _utc_timestamp())
    flattened = flatten(layout, backup)
    return UninstallPlan(
        layout=layout,
        zshrc=zshrc,
        backup=backup,
        content=flattened.content,
        zshrc_mode=zshrc_mode,
        export_names=flattened.export_names,
        secret_names=flattened.secret_names,
        secrets_content=flattened.secrets_content,
        secrets_path=flattened.secrets_path,
        shlib_files=flattened.shlib_files,
        warnings=tuple(warnings),
        zshrc_exists=zshrc_exists,
    )


def apply_uninstall(plan: UninstallPlan) -> UninstallReport:
    """Apply a validated uninstallation plan.

    The secrets file is written first inside the old tree, then the flattened
    ``.zshrc``, and finally the old tree is renamed. ``secrets.sh`` therefore
    moves atomically with the backup. If the rename fails, the secrets file is
    still in the old tree while the new ``.zshrc`` already points at the
    missing backup path; the error names both.

    Args:
        plan: Plan returned by :func:`plan_uninstall`.

    Returns:
        A report describing the flattened file and the backup.

    Raises:
        ShlibError: If the secrets file or the flattened file cannot be written
            or the tree cannot be moved to its backup location.
    """
    if plan.secrets_content is not None:
        secrets_file = plan.layout.root / SECRETS_NAME
        try:
            atomic_write(secrets_file, plan.secrets_content, 0o600)
        except OSError as exc:
            raise ShlibError(
                f"cannot write {secrets_file}: {exc}; {plan.zshrc} and {plan.layout.root} were left unchanged"
            ) from exc

    try:
        atomic_write(plan.zshrc, plan.content, plan.zshrc_mode)
    except OSError as exc:
        if plan.secrets_content is not None:
            raise ShlibError(
                f"cannot write {plan.zshrc}: {exc}; {plan.layout.root / SECRETS_NAME} remains in {plan.layout.root}"
            ) from exc
        raise ShlibError(f"cannot write {plan.zshrc}: {exc}") from exc

    try:
        plan.layout.root.rename(plan.backup)
    except OSError as exc:
        if plan.secrets_content is not None:
            raise ShlibError(
                f"wrote {plan.zshrc}, but could not move {plan.layout.root} to {plan.backup}: {exc}; "
                f"{plan.layout.root / SECRETS_NAME} remains in {plan.layout.root}, while {plan.zshrc} "
                f"sources {plan.secrets_path}, which does not exist yet; "
                f"remove {plan.layout.root} manually after checking the backup"
            ) from exc
        raise ShlibError(
            f"wrote {plan.zshrc}, but could not move {plan.layout.root} to {plan.backup}: {exc}; "
            f"remove {plan.layout.root} manually after checking the backup"
        ) from exc

    return UninstallReport(
        zshrc=plan.zshrc,
        backup=plan.backup,
        export_names=plan.export_names,
        secret_names=plan.secret_names,
        secrets_path=plan.secrets_path,
        shlib_files=plan.shlib_files,
        warnings=plan.warnings,
    )


def _read_exports(directory: Path) -> _Exports:
    """Read export files and split them into public and owner-only exports."""
    if not directory.exists():
        return _Exports((), (), (), ())
    if not directory.is_dir():
        raise ShlibError(f"{directory} is not a directory")

    public_names: list[str] = []
    public_lines: list[bytes] = []
    secret_names: list[str] = []
    secret_lines: list[bytes] = []
    try:
        entries = sorted(directory.iterdir(), key=lambda entry: entry.name)
    except OSError as exc:
        raise ShlibError(f"cannot list {directory}: {exc}") from exc

    for entry in entries:
        if entry.name.startswith(".") or not entry.is_file():
            continue
        if _EXPORT_NAME.fullmatch(entry.name) is None:
            raise ShlibError(f"invalid export name in {entry}: names must match [A-Za-z_][A-Za-z0-9_]*")
        try:
            data = entry.read_bytes()
            mode = stat.S_IMODE(entry.stat().st_mode)
        except OSError as exc:
            raise ShlibError(f"cannot read {entry}: {exc}") from exc
        line = _render_export(entry.name, data, entry)
        if mode & 0o077 == 0:
            secret_names.append(entry.name)
            secret_lines.append(line)
        else:
            public_names.append(entry.name)
            public_lines.append(line)

    return _Exports(
        public_names=tuple(public_names),
        public_lines=tuple(public_lines),
        secret_names=tuple(secret_names),
        secret_lines=tuple(secret_lines),
    )


def _render_export(name: str, data: bytes, path: Path) -> bytes:
    """Render one ``export`` line with the same quoting for every export."""
    if b"\0" in data:
        raise ShlibError(f"{path} contains a NUL byte, which cannot be exported as a shell variable")
    value = data.rstrip(b"\n").decode("utf-8", errors="surrogateescape")
    quoted = shlex.quote(value).encode("utf-8", errors="surrogateescape")
    return b"export " + name.encode("ascii") + b"=" + quoted + b"\n"


def _secret_block(secrets_path: Path, count: int) -> list[bytes]:
    """Return the comment and source block for owner-only exports."""
    backup_name = secrets_path.parent.name
    display_path = f"~/{backup_name}/{SECRETS_NAME}"
    source_path = f"$HOME/{backup_name}/{SECRETS_NAME}"
    return [
        b"# >>> shlib uninstall: secrets\n",
        f"# {count} owner-only export file(s) were not flattened into this file.\n".encode(),
        f"# They are stored in {display_path} (mode 0600)\n".encode(),
        b"# and are sourced below. That directory is a backup and is now part of your\n",
        b"# shell configuration. Keep it, or move the file and update this line yourself.\n",
        f'source "{source_path}"\n'.encode(),
        b"# <<< shlib uninstall: secrets\n",
    ]


def _read_shlibs(directory: Path) -> tuple[tuple[Path, ...], list[bytes]]:
    """Read sourced shlib files and return their paths and framed contents."""
    try:
        entries = sorted(directory.iterdir(), key=lambda entry: entry.name)
    except OSError as exc:
        raise ShlibError(f"cannot list {directory}: {exc}") from exc

    files: list[Path] = []
    chunks: list[bytes] = []
    for entry in entries:
        if len(entry.name) < 2 or not entry.name[:2].isdigit() or not entry.name[:2].isascii():
            continue
        if not entry.is_file():
            continue
        try:
            text = entry.read_text(encoding="utf-8", errors="surrogateescape")
        except OSError as exc:
            raise ShlibError(f"cannot read {entry}: {exc}") from exc
        data = text.encode("utf-8", errors="surrogateescape")
        files.append(entry)
        chunks.append(f"# >>> shlibs/{entry.name}\n".encode())
        chunks.append(data)
        if data and not data.endswith(b"\n"):
            chunks.append(b"\n")
        chunks.append(f"# <<< shlibs/{entry.name}\n".encode())
    return tuple(files), chunks


def _backup_path(root: Path, timestamp: str) -> Path:
    """Return a free backup path for the former shlib root."""
    base = f"{root.name}.uninstalled-{timestamp}"
    candidate = root.parent / base
    counter = 0
    while candidate.exists() or candidate.is_symlink():
        counter += 1
        candidate = root.parent / f"{base}-{counter}"
    return candidate


def _utc_timestamp() -> str:
    """Return the current UTC time as ``YYYYMMDDTHHMMSSZ``."""
    return datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")

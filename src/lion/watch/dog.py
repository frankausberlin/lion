"""Managed watchdog shlib file for ``lion watch-dog``."""

from __future__ import annotations

from pathlib import Path

from lion.shlib.files import atomic_write
from lion.shlib.layout import ShlibLayout
from lion.watch.errors import WatchDogError

WATCHDOG_NAME = "99-lion-watchdog.sh"
WATCHDOG_MODE = 0o644
WATCHDOG_CONTENT = b"# Generated by `lion watch-dog`; do not edit.\ncommand -v lion >/dev/null 2>&1 && lion watch\n"

ON = "on"
OFF = "off"


def watchdog_path(layout: ShlibLayout) -> Path:
    """Return the managed watchdog file path.

    Args:
        layout: Paths below the selected home directory.

    Returns:
        The watchdog path below ``shlibs/``.
    """
    return layout.shlibs / WATCHDOG_NAME


def enable(layout: ShlibLayout) -> Path:
    """Write the watchdog file atomically, replacing any existing entry.

    Args:
        layout: Paths below the selected home directory.

    Returns:
        The written watchdog path.

    Raises:
        WatchDogError: If ``shlibs/`` is missing, symlinked or not a directory,
            or if the file cannot be written.
    """
    _require_shlibs(layout, missing_hint="run `lion shlib install`")
    path = watchdog_path(layout)
    try:
        atomic_write(path, WATCHDOG_CONTENT, WATCHDOG_MODE)
    except OSError as exc:
        raise WatchDogError(f"cannot write {path}: {exc}") from exc
    return path


def disable(layout: ShlibLayout) -> bool:
    """Delete the complete watchdog file, if it exists.

    Args:
        layout: Paths below the selected home directory.

    Returns:
        Whether the file existed and was removed.

    Raises:
        WatchDogError: If ``shlibs/`` is symlinked or not a directory, or if
            the path is a directory or cannot be removed.
    """
    if not _require_shlibs(layout, missing_hint=None):
        return False
    path = watchdog_path(layout)
    if path.is_symlink():
        try:
            path.unlink()
        except OSError as exc:
            raise WatchDogError(f"cannot remove {path}: {exc}") from exc
        return True
    if not path.exists():
        return False
    if path.is_dir():
        raise WatchDogError(f"watchdog path is a directory: {path}")
    try:
        path.unlink()
    except OSError as exc:
        raise WatchDogError(f"cannot remove {path}: {exc}") from exc
    return True


def status(layout: ShlibLayout) -> str:
    """Return ``on`` or ``off`` from the watchdog path state.

    Args:
        layout: Paths below the selected home directory.

    Returns:
        ``on`` for a regular file or symlink, ``off`` for a missing path or a
        missing ``shlibs/`` directory.

    Raises:
        WatchDogError: If ``shlibs/`` is symlinked or not a directory, or if
            the watchdog path is a directory.
    """
    if _require_shlibs(layout, missing_hint=None):
        path = watchdog_path(layout)
        if path.is_dir() and not path.is_symlink():
            raise WatchDogError(f"watchdog path is a directory: {path}")
        if path.is_symlink() or path.is_file():
            return ON
    return OFF


def _require_shlibs(layout: ShlibLayout, *, missing_hint: str | None) -> bool:
    """Return whether ``shlibs/`` is a real directory.

    Args:
        layout: Paths below the selected home directory.
        missing_hint: Hint appended when the directory is missing, or ``None``
            to treat a missing directory as ``False``.

    Returns:
        ``True`` when ``shlibs/`` is a real directory, ``False`` when it is
        missing and ``missing_hint`` is ``None``.

    Raises:
        WatchDogError: If ``shlibs/`` is symlinked or not a directory.
    """
    shlibs = layout.shlibs
    if shlibs.is_symlink():
        raise WatchDogError(f"{shlibs} is a symlink; shlib does not support symlinked directories")
    if not shlibs.exists():
        if missing_hint is None:
            return False
        raise WatchDogError(f"{shlibs} does not exist; {missing_hint}")
    if not shlibs.is_dir():
        raise WatchDogError(f"{shlibs} is not a directory")
    return True
